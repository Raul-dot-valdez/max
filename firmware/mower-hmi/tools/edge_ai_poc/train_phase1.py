#!/usr/bin/env python3
"""Edge-AI PoC phase 1: health classifier on synthetic mower J1939 windows.

Input : windows.npz from tools/mower_j1939_synth (x: N×60×9, y: class, meta: machine|session|time)
Output (in --out):
  model.h5, saved_model/          Keras model (inputs accepted by GD32 Embedded AI: H5 / SavedModel)
  model_fp32.tflite               float TFLite
  model_int8.tflite               full-integer TFLite (int8 in/out), calibrated on training windows
  calib.npz                       calibration set for the GD32 tool's quantizer (x normalised, y)
  scaler.json, ai_scaler.h        feature normalisation used by both firmware paths
  model_int8_tflite.h             model as a C array for the STM32H743 path (TFLite Micro)
  report.json, PHASE1_REPORT.md   metrics: float vs int8 vs rules baseline, size, compute estimate

Run with a Python that has TensorFlow:  python train_phase1.py --windows <windows.npz> --out <dir>
"""
import argparse
import json
import os
import time

import numpy as np

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import tensorflow as tf  # noqa: E402

SEED = 1234
FEATURES = ["rpm", "load_pct", "coolant_c", "oil_press_kpa", "fuel_rate_lph",
            "hyd_oil_c", "ambient_c", "wheel_speed_kmh", "blade_engaged"]


def group_split(meta, seed, frac=(0.70, 0.15, 0.15)):
    """Split by machine|session so no session appears in two sets (prevents leakage)."""
    keys = np.array(["|".join(m.split("|")[:2]) for m in meta])
    groups = np.unique(keys)
    rng = np.random.default_rng(seed)
    rng.shuffle(groups)
    n = len(groups)
    a, b = int(n * frac[0]), int(n * (frac[0] + frac[1]))
    sets = [set(groups[:a]), set(groups[a:b]), set(groups[b:])]
    return [np.where(np.isin(keys, list(s)))[0] for s in sets]


def macro_f1(y, p, k):
    f1s = []
    for c in range(k):
        tp = np.sum((p == c) & (y == c))
        fp = np.sum((p == c) & (y != c))
        fn = np.sum((p != c) & (y == c))
        f1s.append(0.0 if tp == 0 else 2 * tp / (2 * tp + fp + fn))
    return float(np.mean(f1s)), [round(float(x), 3) for x in f1s]


def confusion(y, p, k):
    m = np.zeros((k, k), dtype=int)
    for a, b in zip(y, p):
        m[a, b] += 1
    return m.tolist()


def rules_baseline(x_raw):
    """Hand-written thresholds on the last sample of each window: what a firmware engineer
    would write without ML. Classes: 0 normal, 1 screen_clog, 2 low_oil, 3 hyd_overheat, 4 dull_blades."""
    last = x_raw[:, -1, :]
    rpm, load, cool, oilp, fuel, hyd, amb, spd, blade = [last[:, i] for i in range(9)]
    out = np.zeros(len(last), dtype=int)
    out[hyd > 90] = 3
    out[(blade > 0.5) & (cool > 95)] = 1
    out[(rpm > 2000) & (oilp < 150)] = 2
    return out


def build_model(kind, k, batch=None):
    """M1a 'lstm': matches the phase-1 plan; full-int8 conversion crashes in TF 2.21, so it is
    exported in float for vendor quantizers (GD32 Embedded AI, ST Edge AI).
    M1b 'cnn': 1-D CNN with mature int8 support in TFLite Micro / CMSIS-NN; verified int8 here."""
    inp = tf.keras.Input(shape=(60, 9), batch_size=batch, name="window")
    if kind == "lstm":
        h = tf.keras.layers.LSTM(24, name="lstm")(inp)
    else:
        h = tf.keras.layers.Conv1D(16, 5, strides=2, activation="relu", name="conv1")(inp)
        h = tf.keras.layers.Conv1D(24, 5, strides=2, activation="relu", name="conv2")(h)
        h = tf.keras.layers.GlobalAveragePooling1D(name="gap")(h)
    h = tf.keras.layers.Dense(16, activation="relu", name="dense")(h)
    out = tf.keras.layers.Dense(k, activation="softmax", name="probs")(h)
    return tf.keras.Model(inp, out, name=f"m1_{kind}")


def macs_of(kind, k):
    if kind == "lstm":
        return 60 * 4 * 24 * (9 + 24) + 24 * 16 + 16 * k
    return 28 * 16 * 5 * 9 + 12 * 24 * 5 * 16 + 24 * 16 + 16 * k


def train(kind, k, xtr, ytr, xva, yva, cw, epochs):
    tf.keras.utils.set_random_seed(SEED)
    m = build_model(kind, k)
    m.compile(optimizer=tf.keras.optimizers.Adam(2e-3), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    m.fit(xtr, ytr, validation_data=(xva, yva), epochs=epochs, batch_size=128, class_weight=cw, verbose=0,
          callbacks=[tf.keras.callbacks.EarlyStopping(patience=3, restore_best_weights=True)])
    fixed = build_model(kind, k, batch=1)
    fixed.set_weights(m.get_weights())
    return m, fixed


def c_array(name, data):
    lines = [f"/* Generated by train_phase1.py. Do not edit. */",
             f"#include <stdint.h>", f"alignas(16) const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", f"const unsigned int {name}_len = {len(data)};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--windows", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--epochs", type=int, default=12)
    ap.add_argument("--keep-dull-blades", action="store_true",
                    help="keep dull_blades as a window class (default: merged into normal; it is a multi-day trend, see report)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    tf.keras.utils.set_random_seed(SEED)

    z = np.load(a.windows)
    x_raw, y, meta = z["x"].astype(np.float32), z["y"].astype(int), z["meta"]
    classes = [str(c) for c in z["classes"]]
    if not a.keep_dull_blades and "dull_blades" in classes:
        d = classes.index("dull_blades")
        y = np.where(y == d, 0, y)
        y = np.where(y > d, y - 1, y)
        classes = [c for c in classes if c != "dull_blades"]
    k = len(classes)
    tr, va, te = group_split(meta, SEED)

    mean = x_raw[tr].reshape(-1, 9).mean(0)
    std = x_raw[tr].reshape(-1, 9).std(0) + 1e-6
    norm = lambda v: ((v - mean) / std).astype(np.float32)
    xtr, xva, xte = norm(x_raw[tr]), norm(x_raw[va]), norm(x_raw[te])
    ytr, yva, yte = y[tr], y[va], y[te]

    counts = np.bincount(ytr, minlength=k)
    cw = {c: float(len(ytr) / (k * max(1, counts[c]))) for c in range(k)}

    results = {}
    t0 = time.time()
    m_lstm, lstm_fixed = train("lstm", k, xtr, ytr, xva, yva, cw, a.epochs)
    m_cnn, cnn_fixed = train("cnn", k, xtr, ytr, xva, yva, cw, a.epochs)
    train_s = time.time() - t0
    for kind, m in (("lstm", m_lstm), ("cnn", m_cnn)):
        p = np.argmax(m.predict(xte, batch_size=512, verbose=0), axis=1)
        f, per = macro_f1(yte, p, k)
        results[kind] = {"float_macro_f1": round(f, 4), "float_per_class_f1": dict(zip(classes, per)),
                         "float_accuracy": round(float((p == yte).mean()), 4), "params": int(m.count_params()),
                         "macs_per_inference": macs_of(kind, k)}
    p_float = np.argmax(m_cnn.predict(xte, batch_size=512, verbose=0), axis=1)
    p_rules = rules_baseline(x_raw[te])
    f_rules, per_rules = macro_f1(yte, p_rules, k)
    lo = classes.index("low_oil") if "low_oil" in classes else -1

    # --- exports: float models for vendor tools (both), int8 for the CNN ------------
    for kind, fm in (("lstm", lstm_fixed), ("cnn", cnn_fixed)):
        d = os.path.join(a.out, kind)
        os.makedirs(d, exist_ok=True)
        fm.save(os.path.join(d, "model.h5"))
        fm.export(os.path.join(d, "saved_model"), verbose=False)
        b = tf.lite.TFLiteConverter.from_keras_model(fm).convert()
        open(os.path.join(d, "model_fp32.tflite"), "wb").write(b)
        results[kind]["fp32_tflite_bytes"] = len(b)
    model = cnn_fixed

    rng = np.random.default_rng(SEED)
    calib_idx = np.concatenate([rng.choice(np.where(ytr == c)[0], size=min(80, (ytr == c).sum()), replace=False)
                                for c in range(k) if (ytr == c).sum() > 0])
    calib = xtr[calib_idx]

    def rep():
        for i in range(len(calib)):
            yield [calib[i:i + 1]]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tfl_int8 = conv.convert()
    tfl_fp32 = open(os.path.join(a.out, "cnn", "model_fp32.tflite"), "rb").read()
    open(os.path.join(a.out, "cnn", "model_int8.tflite"), "wb").write(tfl_int8)

    # --- int8 evaluation -----------------------------------------------------------
    itp = tf.lite.Interpreter(model_content=tfl_int8)
    itp.allocate_tensors()
    ind, outd = itp.get_input_details()[0], itp.get_output_details()[0]
    s_in, z_in = ind["quantization"]
    s_out, z_out = outd["quantization"]
    p_int8 = np.zeros(len(xte), dtype=int)
    agree = 0
    t0 = time.time()
    for i in range(len(xte)):
        q = np.clip(np.round(xte[i:i + 1] / s_in + z_in), -128, 127).astype(np.int8)
        itp.set_tensor(ind["index"], q)
        itp.invoke()
        p_int8[i] = int(np.argmax(itp.get_tensor(outd["index"])[0]))
        agree += p_int8[i] == p_float[i]
    host_ms = (time.time() - t0) / len(xte) * 1000
    f_float = results["cnn"]["float_macro_f1"]
    per_float = list(results["cnn"]["float_per_class_f1"].values())
    f_int8, per_int8 = macro_f1(yte, p_int8, k)
    # deployed design: physics rules for screen clog / hydraulic overheat, int8 CNN for low oil
    p_hyb = np.where(p_int8 == lo, lo, p_rules)
    p_hyb = np.where(np.isin(p_rules, [classes.index("screen_clog"), classes.index("hyd_overheat")]), p_rules, p_hyb)
    f_hyb, per_hyb = macro_f1(yte, p_hyb, k)
    ops = sorted({d["op_name"] for d in itp._get_ops_details()})

    # --- firmware artefacts ----------------------------------------------------------
    np.savez(os.path.join(a.out, "calib.npz"), x=calib, y=ytr[calib_idx])
    scaler = {"features": FEATURES, "mean": mean.round(6).tolist(), "std": std.round(6).tolist(),
              "input_scale": float(s_in), "input_zero_point": int(z_in),
              "output_scale": float(s_out), "output_zero_point": int(z_out), "classes": classes,
              "window_s": 60, "sample_hz": 1}
    json.dump(scaler, open(os.path.join(a.out, "scaler.json"), "w"), indent=2)
    with open(os.path.join(a.out, "ai_scaler.h"), "w") as f:
        f.write("/* Generated by train_phase1.py. Do not edit. Feature order: " + ", ".join(FEATURES) + " */\n")
        f.write("#ifndef AI_SCALER_H\n#define AI_SCALER_H\n#define AI_N_FEAT 9\n#define AI_WINDOW 60\n#define AI_N_CLASS %d\n" % k)
        f.write("static const float AI_MEAN[AI_N_FEAT] = {%s};\n" % ", ".join(f"{v:.6f}f" for v in mean))
        f.write("static const float AI_STD[AI_N_FEAT] = {%s};\n" % ", ".join(f"{v:.6f}f" for v in std))
        f.write("#define AI_IN_SCALE %.9ff\n#define AI_IN_ZERO %d\n#define AI_OUT_SCALE %.9ff\n#define AI_OUT_ZERO %d\n" % (s_in, z_in, s_out, z_out))
        f.write("#endif\n")
    open(os.path.join(a.out, "model_int8_tflite.h"), "w").write(c_array("g_ai_model_int8", tfl_int8))

    params = int(model.count_params())
    macs = macs_of("cnn", k)
    report = {
        "split_windows": {"train": int(len(tr)), "val": int(len(va)), "test": int(len(te))},
        "train_class_counts": {classes[c]: int(counts[c]) for c in range(k)},
        "test_class_counts": {classes[c]: int((yte == c).sum()) for c in range(k)},
        "candidates": results,
        "deployment_model": "cnn (M1b)",
        "macro_f1": {"cnn_float": round(f_float, 4), "cnn_int8": round(f_int8, 4), "lstm_float": results["lstm"]["float_macro_f1"], "rules_baseline": round(f_rules, 4), "hybrid_rules_plus_cnn_int8": round(f_hyb, 4)},
        "per_class_f1": {"float": dict(zip(classes, per_float)), "int8": dict(zip(classes, per_int8)), "rules": dict(zip(classes, per_rules)), "hybrid": dict(zip(classes, per_hyb))},
        "accuracy": {"cnn_float": round(float((p_float == yte).mean()), 4), "cnn_int8": round(float((p_int8 == yte).mean()), 4)},
        "int8_float_agreement": round(agree / len(xte), 4),
        "confusion_int8": confusion(yte, p_int8, k),
        "model": {"params": params, "int8_tflite_bytes": len(tfl_int8), "fp32_tflite_bytes": len(tfl_fp32),
                  "tflite_ops": ops, "macs_per_inference": macs},
        "estimates_cortex_m7": {
            "assumption": "int8 CNN with CMSIS-NN-class kernels at 2-4 cycles per MAC incl. overhead; not measured on hardware",
            "stm32h743_480mhz_ms": [round(macs * 2 / 480e3, 2), round(macs * 4 / 480e3, 2)],
            "gd32h759_600mhz_ms": [round(macs * 2 / 600e3, 2), round(macs * 4 / 600e3, 2)],
        },
        "host_int8_ms_per_window": round(host_ms, 3), "train_seconds": round(train_s, 1),
        "tensorflow": tf.__version__,
        "notes": ["Full-int8 conversion of the LSTM crashed (segfault) in this TensorFlow version; LSTM exported in float for vendor quantizers.",
                  "hyd_overheat labels derive from visible hydraulic temperature, so that class is easy by construction.",
                  "dull_blades merged into normal unless --keep-dull-blades: a weeks-long drift is invisible in 60 s windows (F1 about 0.2 when kept)."],
    }
    json.dump(report, open(os.path.join(a.out, "report.json"), "w"), indent=2)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
